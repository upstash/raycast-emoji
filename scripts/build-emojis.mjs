// Generates src/emojis.ts, the emoji metadata bundled with the extension.
// Vector indexes store only an ID and a vector, so names and descriptions ship
// with the extension and a search needs one embedding call and one VECTOR.QUERY.
import { readFile, writeFile } from "fs/promises";
import { clockTime, describe, loadEnrichment } from "./embedding-text.mjs";

// Shown before the user types, so the grid is never empty.
const POPULAR = [
    "😂", "❤️", "🤣", "👍", "😭", "🙏", "😘", "🥰", "😍", "😊",
    "🎉", "😁", "💕", "🥺", "😅", "🔥", "🤔", "😎", "🙌", "👀",
    "✨", "🚀", "💯", "🤯", "😴", "☕", "🐛", "✅", "👏", "💀",
];

const data = JSON.parse(await readFile("./data/emoji_data.json", "utf-8"));
const enrichment = await loadEnrichment();

// Gendered variants of one emoji share a group, so search shows the best one:
// "man technologist", "woman technologist" and "technologist" -> "technologist".
function variantGroup(name) {
    if (/^(flag|keycap):/.test(name)) return name;
    return name
        .replace(/^(man|woman|person|men|women|people) /, "")
        .replace(/:.*\b(man|woman|person|men|women|boy|girl|skin tone)\b.*$/, "");
}

const emojis = data.map((entry) => {
    const name = entry.metadata.originalDescription;
    return {
        emoji: entry.metadata.emoji,
        name,
        description: describe(entry, enrichment),
        group: variantGroup(name),
        clock: clockTime(name) !== null,
    };
});

const known = new Set(emojis.map((entry) => entry.emoji));
const missing = POPULAR.filter((emoji) => !known.has(emoji));
if (missing.length > 0) {
    throw new Error(`Popular emojis missing from data/emoji_data.json: ${missing.join(" ")}`);
}

const header = "// Generated by scripts/build-emojis.mjs from data/. Do not edit.\n";

await writeFile("./src/emojis.ts", `${header}
export interface EmojiEntry {
  emoji: string;
  name: string;
  description: string;
  /** Shared by gendered variants of the same emoji. */
  group: string;
  /** Analog clock face (🕐 to 🕧). */
  clock: boolean;
}

export const POPULAR: string[] = ${JSON.stringify(POPULAR)};

export const EMOJIS: EmojiEntry[] = ${JSON.stringify(emojis)};
`);

console.log(`Wrote ${emojis.length} emojis and ${POPULAR.length} popular picks`);
